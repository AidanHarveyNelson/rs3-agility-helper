"""Turn obstacle models extracted with rsmv into outline shapes for the plugin.

Extract the models first (see tools/README.md), then run:

    python tools/model_to_shape.py <rsmv models dir> <course> 68103 68104 ...

This writes models/<course>.lua (e.g. models/gnome_stronghold.lua), next to
the course's data in courses/<course>.lua. For each model id it reads
models-<id>.json from the rsmv output, welds duplicate vertices, and
keeps the edges that show the model's form: open edges, and creases where the
two faces meet at more than CREASE_DEGREES. The result is written as a Lua
module mapping model id -> { positions = { {x, y, z}, ... }, lines = { ... } },
in model units (512 per tile, y up), with 0-based line indices as ShapeData
expects.
"""

import json
import math
import re
import sys
from pathlib import Path

CREASE_DEGREES = 35


def read_buffer(text):
    """Parse an rsmv buffer string such as 'buffer short[3][]{1,2,3}'."""
    return [int(v) for v in re.search(r"\{(.*)\}", text).group(1).split(",") if v]


def load_triangles(path):
    model = json.loads(Path(path).read_text())
    meshes = model["meshdata"]
    if isinstance(meshes, dict):
        meshes = [meshes]

    vertices, triangles = [], []
    for mesh in meshes:
        flat = read_buffer(mesh["positionBuffer"])
        base = len(vertices)
        vertices += [tuple(flat[i:i + 3]) for i in range(0, len(flat), 3)]
        for render in mesh["renders"]:
            idx = read_buffer(render["buf"])
            triangles += [tuple(base + i for i in idx[t:t + 3]) for t in range(0, len(idx), 3)]
    return vertices, triangles


def outline(vertices, triangles):
    # Weld vertices that share a position (models repeat them per face).
    welded, index_of = [], {}
    remap = []
    for v in vertices:
        if v not in index_of:
            index_of[v] = len(welded)
            welded.append(v)
        remap.append(index_of[v])

    def normal(a, b, c):
        u = [welded[b][i] - welded[a][i] for i in range(3)]
        w = [welded[c][i] - welded[a][i] for i in range(3)]
        n = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]]
        length = math.sqrt(sum(x * x for x in n))
        return [x / length for x in n] if length else None

    edge_normals = {}
    for tri in triangles:
        a, b, c = (remap[i] for i in tri)
        if len({a, b, c}) < 3:
            continue
        n = normal(a, b, c)
        if n is None:
            continue
        for p, q in ((a, b), (b, c), (c, a)):
            edge_normals.setdefault((min(p, q), max(p, q)), []).append(n)

    cos_limit = math.cos(math.radians(CREASE_DEGREES))
    kept = []
    for edge, normals in edge_normals.items():
        if len(normals) != 2:
            kept.append(edge)  # open edge, or where several faces meet
        elif sum(x * y for x, y in zip(*normals)) < cos_limit:
            kept.append(edge)  # crease

    # Keep only the vertices the kept edges use, renumbered from 0.
    used = sorted({i for edge in kept for i in edge})
    new_index = {old: new for new, old in enumerate(used)}
    positions = [welded[i] for i in used]
    lines = [new_index[i] for edge in sorted(kept) for i in edge]
    return positions, lines


def to_lua(shapes):
    out = [
        "-- Generated by tools/model_to_shape.py from models extracted with rsmv.",
        "-- Do not edit by hand. Model units: 512 per tile, y up.",
        "return {",
    ]
    for model_id, (positions, lines) in shapes.items():
        out.append(f"    [{model_id}] = {{")
        out.append("        positions = {")
        for i in range(0, len(positions), 6):
            out.append("            " + " ".join(f"{{ {x}, {y}, {z} }}," for x, y, z in positions[i:i + 6]))
        out.append("        },")
        out.append("        lines = {")
        for i in range(0, len(lines), 24):
            out.append("            " + ", ".join(map(str, lines[i:i + 24])) + ",")
        out.append("        },")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    models_dir, course, ids = Path(sys.argv[1]), sys.argv[2], sys.argv[3:]
    output = Path(__file__).resolve().parent.parent / "models" / f"{course}.lua"
    shapes = {}
    for model_id in ids:
        positions, lines = outline(*load_triangles(models_dir / f"models-{model_id}.json"))
        shapes[int(model_id)] = (positions, lines)
        print(f"{model_id}: {len(positions)} points, {len(lines) // 2} lines")
    output.write_text(to_lua(shapes), newline="\n")


if __name__ == "__main__":
    main()
